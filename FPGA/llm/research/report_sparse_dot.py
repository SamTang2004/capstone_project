"""Generate the sparse-dot research result record from completed local runs."""
from pathlib import Path
import csv
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]


def main():
    run = ROOT / "build/sparse_dot"
    log = (run / "xsim.log").read_text(encoding="utf-8", errors="replace")
    match = re.search(r"PASS: sparse dot8 real DSP48E1 checked=(\d+) cycles=(\d+)", log)
    if not match:
        raise SystemExit("Missing successful DSP simulation marker")
    with (run / "performance.csv").open(newline="") as source:
        rows = list(csv.DictReader(source))
    lookup = {(row["case"], int(row["mode"])): row for row in rows}
    lines = [
        "# Sparse dot8 measured results", "",
        "Generated by `report_sparse_dot.py` from the successful RTL simulation and standalone synthesis reports.", "",
        f"Real DSP48E1 XSim: **{match[1]} completed result vectors across {int(match[2]):,} scoreboard cycles**.",
        "The reference checks 251 declared dot-product results; reset-canceled waves are excluded.", "",
        "## Original-vector scan to result", "",
        "Cycles are accepted command to first sampled result_valid. All original input positions are supplied to every mode.", "",
        "| Fixture | Useful products | Dense cycles | Local finder cycles | Cross-packet cycles | Dense issued products | Cross-packet issued products |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name in ["dense_w8", "half_w8", "ten_percent_w8", "point_one_x_99", "zero_jobs", "short_jobs", "w4_threshold_stalls", "all_thresholded", "int32_wrap"]:
        dense, local, packed = (lookup[name, m] for m in range(3))
        assert dense["useful_products"] == local["useful_products"] == packed["useful_products"]
        assert dense["source_slots"] == local["source_slots"] == packed["source_slots"]
        lines.append(f"| {name} | {dense['useful_products']} | {dense['command_to_result_cycles']} | {local['command_to_result_cycles']} | {packed['command_to_result_cycles']} | {dense['issued_slots']} | {packed['issued_slots']} |")
    extreme = lookup["point_one_x_99", 2]
    occupancy = 100 * int(extreme["useful_products"]) / (8 * int(extreme["command_to_result_cycles"]))
    nonempty = int(extreme["issue_beats"]) - int(extreme["empty_beats"])
    lines += ["", f"In the 0.1% x 99% fixture, packing issues {nonempty} nonempty beat plus {extreme['empty_beats']} empty final beat. The data beat is full; useful utilization over the complete interval is only **{occupancy:.4f}%**.",
              "The common eight-position scanner bounds useful supply. Reduced issue count has not produced a latency win in these fixtures.", "",
              "## Standalone synthesis", "",
              "| Mode | LUTs | Registers | DSPs | BRAM | Setup WNS (ns) | Hold WHS (ns) |",
              "| --- | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for mode, label in enumerate(["Dense", "Local finder", "Cross-packet"]):
        folder = ROOT / f"build/sparse_dot_synth/mode{mode}"
        utilization = (folder / "utilization.rpt").read_text(encoding="utf-8", errors="replace")
        timing = (folder / "timing_synth.rpt").read_text(encoding="utf-8", errors="replace")
        def resource(pattern):
            return int(re.search(pattern, utilization).group(1))
        lut = resource(r"\| Slice LUTs\*\s*\|\s*(\d+)")
        ff = resource(r"\| Slice Registers\s*\|\s*(\d+)")
        dsp = resource(r"\| DSPs\s*\|\s*(\d+)")
        bram = resource(r"\| Block RAM Tile\s*\|\s*(\d+)")
        setup = re.search(r"Slack \([^)]+\)\s*:\s*([-\d.]+)ns\s*\(required time - arrival time\)", timing).group(1)
        hold = re.search(r"Slack \([^)]+\)\s*:\s*([-\d.]+)ns\s*\(arrival time - required time\)", timing).group(1)
        assert dsp == 8
        lines.append(f"| {label} | {lut} | {ff} | {dsp} | {bram} | {setup} | {hold} |")
    lines += ["", "Device: xc7z020clg400-1. Clock target: 10 ns with 0.300 ns uncertainty. These are unplaced estimates, not timing closure. External IO delays and physical clock location are unspecified; no physical frequency or board speedup is established.",
              "", "The compute wrapper uses an 8-bit paired operand and 3-bit context per packed entry, rather than the earlier generic packer's 32-bit payload and 32-bit tag.",
              "", "Raw cycle measurements: [SPARSE_DOT8_PERFORMANCE.csv](SPARSE_DOT8_PERFORMANCE.csv). Architecture, measurement boundaries and reproduction: [SPARSE_DOT8.md](SPARSE_DOT8.md).", ""]
    target = ROOT / "research/SPARSE_DOT8_RESULTS.md"
    target.write_text("\n".join(lines), encoding="utf-8")
    shutil.copyfile(run / "performance.csv", ROOT / "research/SPARSE_DOT8_PERFORMANCE.csv")
    print(target)


if __name__ == "__main__":
    main()
